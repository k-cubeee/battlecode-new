"""Draft: pick the next champion from match history, and record the roster for the champions.

Each pick scores every champion still open to us (see draftscore.py): its overall win rate, how it
does on this map size, against the enemy champions already shown, with the teammates we already hold,
and in this draft slot. The numbers come from draftdata.py, generated by `advisor.py export`.

With no data (draftdata.GAMES == 0) the score reduces to the hand-written order in tables.PREFS /
PREFS_FAR_3, so the bot drafts exactly like the previous version. Any error in the data-driven path
falls back to that same order.
"""
import cambc
from cambc import game_map
import tables as T
import draftscore as S

FAR_SPAWN_DIST = 50
UNREACHED = 65535
_spawn_dist = None  # cached across draft turns


def spawn_distance():
    """Walking distance from our spawn region to the nearest enemy spawn tile (UNREACHED if none; 0 on error)."""
    global _spawn_dist
    if _spawn_dist is None:
        try:
            block = game_map.walls() | game_map.holes() | game_map.altars()
            field = cambc.DistanceField()
            field.compute(block, game_map.spawn_region(cambc.Team.ALLY), cambc.Bitboard())
            best = UNREACHED
            for v in game_map.spawn_region(cambc.Team.ENEMY).positions():
                d = field.get(v)
                if d < best:
                    best = d
            _spawn_dist = best
        except Exception as error:
            print(f"draft spawn distance error: {error}", flush=True)
            _spawn_dist = 0          # unknown: keep the default (v3) draft
    return _spawn_dist


def map_sig():
    """Map signature shared with advisor.py: width x height."""
    try:
        return f"{game_map.width()}x{game_map.height()}"
    except Exception:
        return None


def load_counts():
    """The advisor's exported counts, or None when there is no usable data."""
    try:
        import draftdata as D
        if getattr(D, "GAMES", 0) <= 0:
            return None
        return {"base": D.BASE, "map": D.MAP, "vs": D.VS, "syn": D.SYN, "slot": D.SLOT}
    except Exception:
        return None


def legacy_pick(prefs, chosen):
    for candidate in prefs:
        if candidate not in chosen:
            return candidate
    return next(p for p in range(T.N_PICKS) if p not in chosen)


def choose(size, chosen, enemy):
    """The pick for this turn. chosen / enemy are lists of draft ids (ints)."""
    far = size == 3 and spawn_distance() >= FAR_SPAWN_DIST
    prefs = T.prefs_for(size, far)
    counts = load_counts()
    if counts is not None:
        try:
            pick = S.best_pick(counts, map_sig(), chosen, enemy, range(T.N_PICKS), S.prior_bonus(prefs))
            if pick is not None:
                print(f"draft: pick {pick} (map {map_sig()}, ours {chosen}, enemy {enemy})", flush=True)
                return pick
        except Exception as error:
            print(f"draft scoring error: {error!r}", flush=True)
    return legacy_pick(prefs, chosen)


def play():
    size = cambc.draft.team_size()
    chosen = [int(p) for p in cambc.draft.current_draft(cambc.Team.ALLY)]
    try:
        enemy = [int(p) for p in cambc.draft.current_draft(cambc.Team.ENEMY)]
    except Exception:
        enemy = []                       # their picks are not visible yet
    pick = choose(size, chosen, enemy)

    # Draft memory layout: [number of bodies, champion type of each body in order].
    bodies = []
    for p in chosen + [pick]:
        bodies.extend(T.bodies_of_pick(p))
    cambc.draft_memory.submit(bytes([len(bodies)] + bodies))
    cambc.draft.pick(pick)
